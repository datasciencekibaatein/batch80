-- subquery inside select
-- show company's average along all the employees records

select
	emp_name,
    salary,
    (select avg(salary) from employees) as avg_salary
from employees;




-- find the employees having maximum salary in their department
select
	emp_name,
    salary,
    department
from employees
where (department,salary) in 
	(select
		department,
		max(salary) max_salary

-- before insert
-- Whenever we insert the employee , increase their salary by ₹1000.

DELIMITER $$
CREATE TRIGGER BEFORE_EMPLOYEE_INSERT
BEFORE INSERT ON EMPLOYEE
FOR EACH ROW
BEGIN
	SET NEW.SALARY = NEW.SALARY + 1000;
END $$

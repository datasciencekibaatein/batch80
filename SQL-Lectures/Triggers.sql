-- Before Update

-- Whenever an employee's salary is updated increase the new salary by 10%.

DELIMITER $$
CREATE TRIGGER BEFORE_EMPLOYEE_UPDATE
BEFORE UPDATE ON EMPLOYEE
FOR EACH ROW
BEGIN
	SET NEW.SALARY = NEW.SALARY * 1.10;
END $$
DELIMITER ;


